#!/usr/bin/env python3
"""Generate a Claude Code mod plugin from a skill plus a small JSON spec.

Usage:
  python3 scaffold_mod.py --skill <skill-folder> --spec <spec.json> --out <new-plugin-folder> [--force]

The skill is copied, untouched, into <out>/skills/<skill-name>/ so the plugin still
carries the full instructions. Around it the script writes:

  .claude-plugin/plugin.json   manifest (with userConfig for the gate)
  hooks/hooks.json             points at the hooks module
  hooks/register.js            the mod: plain JavaScript, safe to edit by hand
  tests/<plugin>.test.ts       tests that run under `claude plugin test`
  README.md                    what it does, modes, and a trust-surface block

It never writes into the source skill folder. Spec format: references/mod-spec.md.
Covers trigger-style mods (gate / prime / command). Panes, bands, model calls and
compaction handoffs are written by hand (see SKILL.md).
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import find_skill_md, parse_frontmatter, plugin_name_problem  # noqa: E402

MODES = ["ask", "block", "nudge", "off"]


def js(value):
    return json.dumps(value, ensure_ascii=False)


def js_escape(word):
    return re.sub(r"[.*+?^${}()|\[\]\\/]", lambda m: "\\" + m.group(0), word)


def command_regex(entry):
    """A command entry: words separated by whitespace, matched anywhere a command can start."""
    if entry.startswith("re:"):
        return entry[3:]
    words = entry.split()
    return r"(?:^|[\s;&|(])" + r"\s+".join(js_escape(w) for w in words) + r"(?![\w-])"


def prose_regex(entry):
    if entry.startswith("re:"):
        return entry[3:]
    words = entry.split()
    return r"(?<![\w-])" + r"\s+".join(js_escape(w) for w in words) + r"(?![\w-])"


def regex_list(sources, flags=""):
    return "[\n" + "".join(f"  new RegExp({js(s)}{', ' + js(flags) if flags else ''}),\n" for s in sources) + "]"


def check_regexes(sources, flags):
    """Compile each regex with Node, if available, so a bad one fails here and not in a session."""
    try:
        r = subprocess.run(
            ["node", "-e", "for (const s of JSON.parse(process.argv[1])) new RegExp(s, process.argv[2])", json.dumps(sources), flags],
            capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        print("note: node not found; regular expressions were not test-compiled", file=sys.stderr)
        return
    if r.returncode != 0:
        lines = [ln for ln in r.stderr.splitlines() if "Error" in ln]
        sys.exit("a regular expression in the spec does not compile: " + (lines[0] if lines else r.stderr.strip()[:200]))


def first_literal(entries):
    for e in entries:
        if not e.startswith("re:"):
            return e
    return None


# ---- templates -------------------------------------------------------------

HEADER = """// Generated by skill-to-mod from the skill "__SKILL__". It is plain code: edit it freely.
//
// __SUMMARY__
//
// A reminder, not a security boundary: it reads text and fails open. The skill
// itself, bundled in skills/__SKILL__/, still does the real work.

const NAME = __NAME__
const SKILL = __SKILL_JS__
const DEFAULT_MODE = __MODE__
const DEFAULT_REQUIRED = __REQUIRED__

// State is per session. Module variables start over when the mod reloads.
let snoozed = false
"""

GATE_TOP = """
// What counts as shipping: a command line that puts work in front of others or into production.
const SHIP = __SHIP__
const MAX_HOLDS = __MAX_HOLDS__

// What has happened since the last edit.
const done = new Set()
let acknowledged = false
let holds = 0

function isShip(command) {
  return SHIP.some((re) => re.test(command))
}

function listRequired(options) {
  const raw = typeof options.required === 'string' ? options.required : DEFAULT_REQUIRED
  return raw.split(',').map((s) => s.trim()).filter((s) => s !== '')
}

// A skill reaches skill.prompt as `name`, or `plugin:name` for a plugin's skill.
function sameSkill(seen, wanted) {
  return seen === wanted || seen.endsWith(':' + wanted)
}
"""

PRIME_TOP = """
// Prompts that say the moment has come.
const PRIME = __PRIME__
"""

REGISTER_OPEN_GATE = """
export function register(on, options) {
  const mode = typeof options.mode === 'string' ? options.mode : DEFAULT_MODE
  const required = listRequired(options)

  function outstanding() {
    return required.filter((name) => !done.has(name))
  }
"""

REGISTER_OPEN_PLAIN = """
export function register(on) {
"""

COMMAND_REGISTER = """
  on('session.start', async ($, e, next) => {
    await $.command.register({
      name: __CMD__,
      description: 'Show __NAME_TEXT__ state, or snooze it with "off" and resume it with "on"',
      argumentHint: '[off|on]',
      immediate: true,
    })
    return next(e)
  })
"""

SKILL_TRACKER = """
  on('skill.prompt', async ($, e, next) => {
    for (const name of required) {
      if (sameSkill(e.skill, name)) {
        done.add(name)
        holds = 0
      }
    }
    $.ui.status(outstanding().length === 0 ? undefined : NAME + ': ' + outstanding().join(', ') + ' still to run')
    return next(e)
  })
"""

STALE_ON_EDIT = """
  on('tool.call', { tool: ['Edit', 'Write', 'MultiEdit', 'NotebookEdit'] }, async ($, e, next) => {
    const ran = await next(e)
    const changed = ran.deny === undefined && ran.isError !== true
    if (changed && (done.size > 0 || acknowledged)) {
      done.clear()
      acknowledged = false
      holds = 0
      $.ui.status(NAME + ': checks are stale after edits (' + required.join(', ') + ')')
    }
    return ran
  }).catch(($, e, next) => next(e)) // fail open: a reminder must never block an edit
"""

GATE_HOOK = """
  on('tool.call', { tool: 'Bash' }, async ($, e, next) => {
    const command = String(e.command ?? '')
    if (mode === 'off' || snoozed || required.length === 0 || !isShip(command)) {
      return next(e)
    }
    const missing = outstanding()
    if (missing.length === 0 || acknowledged) {
      return next(e)
    }
    // Never trap the session: after a couple of holds, let the command through.
    if (holds >= MAX_HOLDS) {
      $.ui.toast(NAME + ': let it through after ' + MAX_HOLDS + ' holds')
      return next(e)
    }
    const instruction =
      NAME + ' held this command: ' + missing.join(', ') + ' has not run__SINCE__. ' +
      'Run ' + (missing.length === 1 ? 'that skill' : 'those skills') + ' on the current changes, fix what it finds, then retry. ' +
      'If a skill is not available, tell the user instead of retrying.'

    if (mode === 'nudge') {
      const ran = await next(e)
      if (ran.deny !== undefined) {
        return ran
      }
      return { ...ran, context: [...(ran.context ?? []), NAME + ': that ran before ' + missing.join(', ') + ' had run__SINCE__. Run ' + (missing.length === 1 ? 'it' : 'them') + ' now.'] }
    }

    if (mode === 'ask') {
      // A question nobody answers counts as "run the checks first".
      let answer = 'Run checks first'
      try {
        answer = await $.ui.ask(
          missing.join(', ') + ' has not run__SINCE__. Run this anyway? ' + command.slice(0, 120),
          ['Run checks first', 'Ship anyway'],
        )
      } catch {
        // dismissed, or nobody is there to ask
      }
      if (answer === 'Ship anyway') {
        acknowledged = true
        return next(e)
      }
    }

    holds += 1
    return { deny: instruction }
  }).catch(($, e, next) => next(e)) // fail open: if the guard breaks, the command runs as it would without it
"""

PRIME_HOOK = """
  on('prompt.submit', async ($, e, next) => {
    if (__PRIME_GUARD__ || !PRIME.some((re) => re.test(e.text))) {
      return next(e)
    }
    const line = __PRIME_LINE__
    return next({ ...e, context: [...(e.context ?? []), line] })
  }).catch(($, e, next) => next(e)) // fail open
"""

COMMAND_HOOK_GATE = """
  on('command.run', { command: __CMD__ }, async ($, e) => {
    const arg = String(e.args ?? '').trim()
    if (arg === 'off') {
      snoozed = true
      $.ui.status(undefined)
      return { text: NAME + ': snoozed. Run /' + __CMD__ + ' on to resume.' }
    }
    if (arg === 'on') {
      snoozed = false
      return { text: NAME + ': back on.' }
    }
    const left = outstanding()
    return {
      text:
        NAME + ' (' + mode + (snoozed ? ', snoozed' : '') + '): ' +
        (required.length - left.length) + ' of ' + required.length + ' checks run__SINCE__' +
        (left.length > 0 ? ', still to run: ' + left.join(', ') : '') +
        (acknowledged ? '. Shipping was acknowledged.' : '.'),
    }
  })
"""

COMMAND_HOOK_PLAIN = """
  on('command.run', { command: __CMD__ }, async ($, e) => {
    const arg = String(e.args ?? '').trim()
    if (arg === 'off') {
      snoozed = true
      return { text: NAME + ': snoozed. Run /' + __CMD__ + ' on to resume.' }
    }
    if (arg === 'on') {
      snoozed = false
      return { text: NAME + ': back on.' }
    }
    return { text: NAME + (snoozed ? ' (snoozed)' : '') + ': nudges Claude toward the ' + SKILL + ' skill when a prompt matches.' }
  })
"""


def fill(template, **kw):
    for k, v in kw.items():
        template = template.replace("__" + k + "__", v)
    return template


def build_register(spec, skill_name, plugin):
    gate, prime = spec.get("gate"), spec.get("prime")
    cmd = spec.get("command", {}).get("name", plugin) if spec.get("command", True) is not False else None
    since = " since the last edit" if (gate or {}).get("staleOnEdit", True) else " yet"

    bits = []
    if gate:
        bits.append("gate: holds a ship command until the required skills have run" + since)
    if prime:
        bits.append("prime: adds one line of context when a prompt matches")
    if cmd:
        bits.append("/" + cmd + ": shows state, snoozes with off")
    out = fill(HEADER, SKILL=skill_name, NAME=js(plugin), SKILL_JS=js(skill_name),
               MODE=js((gate or {}).get("mode", "ask")),
               REQUIRED=js(",".join((gate or {}).get("required", [skill_name]))),
               SUMMARY="Hooks: " + "; ".join(bits))
    if gate:
        out += fill(GATE_TOP, SHIP=regex_list([command_regex(m) for m in gate["match"]]), MAX_HOLDS=str(gate.get("maxHolds", 2)))
    if prime:
        out += fill(PRIME_TOP, PRIME=regex_list([prose_regex(m) for m in prime["match"]], "i"))
    out += REGISTER_OPEN_GATE if gate else REGISTER_OPEN_PLAIN
    if cmd:
        out += fill(COMMAND_REGISTER, CMD=js(cmd), NAME_TEXT=plugin)
    if gate:
        out += SKILL_TRACKER
        if gate.get("staleOnEdit", True):
            out += STALE_ON_EDIT
        out += fill(GATE_HOOK, SINCE=since)
    if prime:
        if gate:
            guard = "mode === 'off' || snoozed || required.length === 0 || outstanding().length === 0"
            default_line = "NAME + ': before shipping, run ' + outstanding().join(', ') + ' on the current changes.'"
        else:
            guard = "snoozed"
            default_line = "NAME + ': the ' + SKILL + ' skill applies here. Use it.'"
        line = js(prime["text"]) if prime.get("text") else default_line
        out += fill(PRIME_HOOK, PRIME_GUARD=guard, PRIME_LINE=line)
    if cmd:
        out += fill(COMMAND_HOOK_GATE if gate else COMMAND_HOOK_PLAIN, CMD=js(cmd), SINCE=since)
    out += "}\n"
    return out


TEST_HEAD = """import { expect, test } from 'claude-code/testing'

// Stands in for Claude Code beneath the mod: every tool "runs" and answers ok,
// and a question to the user (AskUserQuestion) is answered from `answer`.
function engine(on: any, answer: { value: string } = { value: 'Run checks first' }) {
  on('tool.call', ($: any, e: any) =>
    e.tool === 'AskUserQuestion'
      ? { result: { answers: { [e.questions[0].question]: answer.value } } }
      : { result: 'ok' },
  )
  on('skill.prompt', ($: any, e: any) => ({ text: e.text }))
  on('ui.status', () => ({ value: undefined }))
  on('ui.toast', () => ({ value: undefined }))
}
"""

