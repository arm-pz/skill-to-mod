def build_tests(spec, skill_name, plugin):
    gate, prime = spec.get("gate"), spec.get("prime")
    cmd = spec.get("command", {}).get("name", plugin) if spec.get("command", True) is not False else None
    out = TEST_HEAD
    if gate:
        example = gate.get("example") or first_literal(gate["match"])
        stale = TEST_STALE if gate.get("staleOnEdit", True) else ""
        body = fill(TEST_GATE, SHIP_EXAMPLE=js(example), REQUIRED_LIST=js(gate.get("required", [skill_name])), STALE_TEST=stale, CMD=js(cmd or plugin))
        if not cmd:
            body = body[: body.index("test('the command snoozes and resumes it'")]
        out += body
    if prime:
        example = prime.get("example") or first_literal(prime["match"])
        if gate:
            options = "{ options: { mode: 'block' } }, "
            expect = "/" + re.escape((gate.get("required") or [skill_name])[0]) + "/"
        else:
            options = ""
            expect = "/" + re.escape(prime["text"][:20]) + "/" if prime.get("text") else "/" + re.escape(skill_name) + "/"
        out += fill(TEST_PRIME, PRIME_OPTIONS=options, PRIME_EXAMPLE=js(example), PRIME_EXPECT=expect)
    if cmd and not gate:
        out += fill(TEST_PLAIN_COMMAND, CMD=js(cmd))
    return out


def build_manifest(spec, plugin, description):
    manifest = {"name": plugin, "version": spec.get("version", "0.1.0"), "description": description}
    if spec.get("author"):
        manifest["author"] = {"name": spec["author"]}
    manifest["keywords"] = ["mods"] + spec.get("keywords", [])
    if spec.get("gate"):
        gate = spec["gate"]
        manifest["userConfig"] = {
            "mode": {
                "type": "string", "title": "Mode",
                "description": "ask: hold a ship command and ask whether to run the checks first. block: refuse until the checks have run. nudge: let it run and remind Claude afterwards. off: do nothing.",
                "default": gate.get("mode", "ask"), "options": MODES,
            },
            "required": {
                "type": "string", "title": "Required check skills",
                "description": "Comma-separated names of the skills that must have run before a ship command. All of them must have run.",
                "default": ",".join(gate.get("required", [])),
            },
        }
    return manifest


